//! Component registry and dependency injection.
//!
//! This is the Rust counterpart of `backend/core/__init__.py` plus
//! `backend/core/component/*.py`.
//!
//! ## How it works
//!
//! Every `#[service]`, `#[repository]`, `#[datasource("...")]` and
//! `#[controller]` item submits a [`ComponentRegistration`] through
//! [`inventory`], which collects them at link time. No central list has to be
//! edited, which reproduces the "auto discovery + auto registration" feature of
//! the Python project without runtime module scanning.
//!
//! At startup [`AppContext::build_components`](crate::core::context::AppContext::build_components)
//! walks the registrations in layer order — datasource, repository, service,
//! controller — exactly like the Python implementation injected
//! Controller→Service→Repository→Datasource. Each factory resolves its own
//! dependencies from the already-built layers.

use std::any::{Any, TypeId};
use std::collections::HashMap;
use std::sync::Arc;

use anyhow::anyhow;

use crate::core::context::AppContext;

/// The four component layers, in construction order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ComponentKind {
    /// e.g. `mysql`, `redis`.
    Datasource = 0,
    /// Data access objects.
    Repository = 1,
    /// Business services.
    Service = 2,
    /// HTTP controllers.
    Controller = 3,
}

impl ComponentKind {
    /// Lower case label used in logs.
    pub const fn as_str(self) -> &'static str {
        match self {
            ComponentKind::Datasource => "datasource",
            ComponentKind::Repository => "repository",
            ComponentKind::Service => "service",
            ComponentKind::Controller => "controller",
        }
    }

    /// Construction order; dependencies must live in a lower layer.
    pub const fn order(self) -> u8 {
        self as u8
    }
}

/// Type-erased component instance.
pub type ComponentValue = Arc<dyn Any + Send + Sync>;

/// Factory used to build a component once at startup.
pub type BuildFn = fn(&AppContext) -> anyhow::Result<ComponentValue>;

/// Downcast a built component to the controller abstraction, so the router can
/// enumerate controllers without knowing their concrete types.
pub type ControllerCastFn =
    fn(ComponentValue) -> Option<Arc<dyn crate::model::controller::ControllerBase>>;

/// A link-time registration emitted by the component macros.
pub struct ComponentRegistration {
    /// Registry name, the snake_case type name (or the explicit datasource name).
    pub name: &'static str,
    /// Layer this component belongs to.
    pub kind: ComponentKind,
    /// Fully qualified Rust type name, for diagnostics.
    pub type_name: &'static str,
    /// Factory.
    pub build: BuildFn,
    /// Controller downcast hook; `Some` only for `#[controller]` registrations.
    pub as_controller: Option<ControllerCastFn>,
}

inventory::collect!(ComponentRegistration);

/// Constructor injection, generated by `#[derive(Autowired)]`,
/// `#[service]`, `#[repository]`, `#[datasource]` and `#[controller]`.
pub trait Autowire: Sized + Send + Sync + 'static {
    /// Build the component, resolving every injected field from `ctx`.
    fn autowire(ctx: &AppContext) -> anyhow::Result<Self>;
}

/// The built component instances.
#[derive(Default)]
pub struct Container {
    by_name: HashMap<(&'static str, ComponentKind), ComponentValue>,
    by_type: HashMap<TypeId, ComponentValue>,
}

impl std::fmt::Debug for Container {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let mut names: Vec<String> = self
            .by_name
            .keys()
            .map(|(name, kind)| format!("{}:{name}", kind.as_str()))
            .collect();
        names.sort();
        f.debug_struct("Container")
            .field("components", &names)
            .finish()
    }
}

impl Container {
    /// Register a component under its name, layer and Rust type.
    ///
    /// Names only have to be unique inside a layer, exactly like the four
    /// independent registries of the Python implementation.
    pub fn insert(
        &mut self,
        name: &'static str,
        kind: ComponentKind,
        value: ComponentValue,
    ) -> anyhow::Result<()> {
        let type_id = (*value).type_id();
        if self.by_name.contains_key(&(name, kind)) {
            return Err(anyhow!(
                "duplicate {} name `{name}`; component names are derived from the \
                 type name in snake_case, rename one of the types",
                kind.as_str()
            ));
        }
        if self.by_type.contains_key(&type_id) {
            return Err(anyhow!(
                "component `{}` of type `{name}` is registered twice",
                kind.as_str()
            ));
        }
        self.by_name.insert((name, kind), Arc::clone(&value));
        self.by_type.insert(type_id, value);
        Ok(())
    }

    /// Resolve a component by type.
    pub fn get<T: Any + Send + Sync>(&self) -> Option<Arc<T>> {
        self.by_type
            .get(&TypeId::of::<T>())
            .and_then(|value| Arc::clone(value).downcast::<T>().ok())
    }

    /// Resolve a component by registry name, looking through every layer in
    /// construction order (datasource, repository, service, controller).
    pub fn get_by_name(&self, name: &str) -> Option<ComponentValue> {
        for kind in [
            ComponentKind::Datasource,
            ComponentKind::Repository,
            ComponentKind::Service,
            ComponentKind::Controller,
        ] {
            if let Some(value) = self.by_name.get(&(name, kind)) {
                return Some(Arc::clone(value));
            }
        }
        None
    }

    /// All registered components as `(layer, name)`, sorted.
    pub fn names(&self) -> Vec<(ComponentKind, &'static str)> {
        let mut names: Vec<(ComponentKind, &'static str)> = self
            .by_name
            .keys()
            .map(|(name, kind)| (*kind, *name))
            .collect();
        names.sort_by(|a, b| a.0.order().cmp(&b.0.order()).then_with(|| a.1.cmp(b.1)));
        names
    }

    /// Number of registered components.
    pub fn len(&self) -> usize {
        self.by_name.len()
    }

    /// Whether no component has been registered.
    pub fn is_empty(&self) -> bool {
        self.by_name.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn duplicate_names_inside_a_layer_are_rejected() {
        let mut container = Container::default();
        container
            .insert(
                "demo",
                ComponentKind::Service,
                Arc::new(String::from("a")) as ComponentValue,
            )
            .unwrap();
        let err = container
            .insert(
                "demo",
                ComponentKind::Service,
                Arc::new(1u8) as ComponentValue,
            )
            .unwrap_err();
        assert!(err.to_string().contains("duplicate service name"));
    }

    #[test]
    fn the_same_name_may_exist_in_different_layers() {
        let mut container = Container::default();
        container
            .insert(
                "demo",
                ComponentKind::Repository,
                Arc::new(String::from("a")) as ComponentValue,
            )
            .unwrap();
        container
            .insert(
                "demo",
                ComponentKind::Service,
                Arc::new(1u8) as ComponentValue,
            )
            .unwrap();
        assert_eq!(container.len(), 2);
        // name lookup walks datasource -> repository -> service -> controller
        assert!(container.get_by_name("demo").is_some());
    }

    #[test]
    fn components_resolve_by_type_and_by_name() {
        #[derive(Debug, PartialEq, Eq)]
        struct Demo(u32);

        let mut container = Container::default();
        container
            .insert(
                "demo",
                ComponentKind::Service,
                Arc::new(Demo(42)) as ComponentValue,
            )
            .unwrap();

        assert_eq!(container.get::<Demo>().unwrap().0, 42);
        assert!(container.get::<String>().is_none());
        assert_eq!(container.names(), vec![(ComponentKind::Service, "demo")]);
        assert!(container.get_by_name("demo").is_some());
    }
}
